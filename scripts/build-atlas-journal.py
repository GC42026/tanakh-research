"""Build the atlas journal index from the published study pages."""
import json
import re
from pathlib import Path
from xml.etree import ElementTree

root = Path(__file__).resolve().parents[1] / "docs"
studies = []
for path in sorted((root / "research").glob("*.html")):
    # These journal pages use well-formed HTML apart from HTML void elements.
    source = re.sub(r"<(meta|link|img|br|hr)\b([^<>]*?)(?<!/)>", r"<\1\2/>", path.read_text())
    page = ElementTree.fromstring(source.replace("<!doctype html>", ""))
    article = page.find(".//article")
    heading = article.find("header")
    links = {
        anchor.attrib["href"]: "".join(anchor.itertext()).strip()
        for anchor in article.findall(".//a")
        if anchor.attrib.get("href", "").startswith("https://")
    }
    studies.append({
        "id": path.stem,
        "title": "".join(heading.find("h1").itertext()),
        "summary": "".join(heading.find("p").itertext()),
        "sources": [{"url": url, "title": title} for url, title in links.items()],
        "related": [
            anchor.attrib["href"].removesuffix(".html")
            for anchor in page.findall(".//nav[@class='related']//li/a")
            if anchor.attrib["href"].endswith(".html")
        ],
    })

(root / "atlas" / "journal.js").write_text(
    "// Generated by scripts/build-atlas-journal.py from docs/research.\n"
    "const journal = " + json.dumps(studies, ensure_ascii=False, indent=2) + ";\n"
)
